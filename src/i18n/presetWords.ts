/** One ready-made word in the app's language, where it is translated. */
export function presetWord(word: string): string {
  return locale() === 'zh-Hans' ? (ZH_HANS[word] ?? word) : word;
}

/** Ready-made words in the app's language, where they are translated. */
export function presetWords(words: readonly string[]): string[] {
  return words.map(presetWord);
}

